class ScopeTimestampUnwrapper:
    """
    Stateful EP83 timestamp unwrapping matching Analyzer Utility 4.2.0.

    The Utility treats the device timestamp as unsigned u32 microseconds,
    ignores 0 and 0xADACABAA, and on wrap adds 0xFFFFFFFF exactly.
    """
    prev_raw: int = 0
    add_factor: int = 0

    def unwrap(self, raw: int) -> Optional[int]:
        raw = int(raw) & 0xFFFFFFFF

        if raw == 0 or raw == SCOPE_TIMESTAMP_SKIP_MAGIC:
            return None

        if raw - self.prev_raw < 0:
            self.add_factor += SCOPE_TIMESTAMP_WRAP_ADD_UTILITY

        unwrapped = raw + self.add_factor
        self.prev_raw = raw
        return unwrapped


@dataclass(frozen=True)
class ScopeSample:
    packet_index: int
    sample_index: int
    timestamp_raw: int
    timestamp_us: int
    vbus_raw: int
    vbus_mV: int
    cc1_raw: int
    cc1_mV: int
    cc2_raw: int
    cc2_mV: int
    ibus_raw: int
    ibus_mA: int

    @property
    def vbus_V(self) -> float:
        return self.vbus_mV / 1000.0

    @property
    def cc1_V(self) -> float:
        return self.cc1_mV / 1000.0

    @property
    def cc2_V(self) -> float:
        return self.cc2_mV / 1000.0

    @property
    def ibus_A(self) -> float:
        return self.ibus_mA / 1000.0

    @property
    def power_W(self) -> float:
        return self.vbus_V * self.ibus_A


@dataclass(frozen=True)
class ScopeTransferDecode:
    """
    Decoded contents of one host EP83 bulk transfer.

    complete_packets:
        Number of complete 64-byte scope packets consumed.
    samples:
        Real samples only. Analyzer Utility's two synthetic graph preamble
        points are intentionally NOT included.
    paddings:
        Bytes 60..63 from each complete packet, preserved verbatim.
    residual:
        Any trailing bytes after the last complete 64-byte packet. Utility
        truncates them; we report them rather than silently losing evidence.
    """
    complete_packets: int
    samples: tuple[ScopeSample, ...]
    paddings: tuple[bytes, ...]
    residual: bytes


@dataclass(frozen=True)
class ScopeGraphPoint:
    """
    Display-only point used to reproduce Analyzer Utility graph initialization.
    This is deliberately separate from ScopeSample so synthetic points can
    never be mistaken for device data.
    """
    timestamp_us: int
    cc1_mV: int
    cc2_mV: int
    ibus_mA: int
    vbus_mV: int


def decode_scope_sample(
    sample: bytes,
    timestamp_state: ScopeTimestampUnwrapper,
    *,
    packet_index: int = 0,
    sample_index: int = 0,
    is_epr: bool = True,
    product_id: int = USB_PID_CY4500_EPR,
) -> Optional[ScopeSample]:
    """
    Decode one confirmed 12-byte EP83 scope sample.

      +0..3   timestamp u32 LE [us]
      +4..5   VBUS raw u16 LE
      +6..7   CC1 raw u16 LE
      +8..9   CC2 raw u16 LE
      +10..11 IBUS raw u16 LE
    """
    sample = bytes(sample)
    if len(sample) != SCOPE_SAMPLE_SIZE:
        raise ValueError(
            f"scope sample must be exactly {SCOPE_SAMPLE_SIZE} bytes, "
            f"got {len(sample)}"
        )

    timestamp_raw = read_u32_le(sample, SCOPE_OFFSET_TIMESTAMP)
    timestamp_us = timestamp_state.unwrap(timestamp_raw)
    if timestamp_us is None:
        return None

    vbus_raw = read_u16_le(sample, SCOPE_OFFSET_VBUS)
    cc1_raw = read_u16_le(sample, SCOPE_OFFSET_CC1)
    cc2_raw = read_u16_le(sample, SCOPE_OFFSET_CC2)
    ibus_raw = read_u16_le(sample, SCOPE_OFFSET_IBUS)

    factor, val_mv = _live_voltage_params(
        is_epr=is_epr,
        product_id=product_id,
    )

    vbus_mV = vbus_raw * val_mv * factor // LIVE_ADC_COUNTS
    cc1_mV = cc1_raw * val_mv // LIVE_ADC_COUNTS
    cc2_mV = cc2_raw * val_mv // LIVE_ADC_COUNTS
    ibus_mA = live_ibus_milliamps(ibus_raw)

    return ScopeSample(
        packet_index=int(packet_index),
        sample_index=int(sample_index),
        timestamp_raw=timestamp_raw,
        timestamp_us=timestamp_us,
        vbus_raw=vbus_raw,
        vbus_mV=vbus_mV,
        cc1_raw=cc1_raw,
        cc1_mV=cc1_mV,
        cc2_raw=cc2_raw,
        cc2_mV=cc2_mV,
        ibus_raw=ibus_raw,
        ibus_mA=ibus_mA,
    )


def decode_scope_transfer(
    data: bytes,
    timestamp_state: Optional[ScopeTimestampUnwrapper] = None,
    *,
    is_epr: bool = True,
    product_id: int = USB_PID_CY4500_EPR,
) -> ScopeTransferDecode:
    """
    Decode complete 64-byte EP83 scope packets from one host bulk transfer.

    Exactly like ScopeCollecter, a non-multiple-of-64 length is truncated to
    the last complete packet for decoding. Unlike the Utility, residual bytes
    are returned to the caller for diagnostics.
    """
    data = bytes(data)
    if timestamp_state is None:
        timestamp_state = ScopeTimestampUnwrapper()

    complete_len = (len(data) // SCOPE_PACKET_SIZE) * SCOPE_PACKET_SIZE
    residual = data[complete_len:]

    samples: list[ScopeSample] = []
    paddings: list[bytes] = []

    packet_count = complete_len // SCOPE_PACKET_SIZE

    for packet_index in range(packet_count):
        base = packet_index * SCOPE_PACKET_SIZE
        packet = data[base : base + SCOPE_PACKET_SIZE]
        paddings.append(packet[SCOPE_PADDING_OFFSET:SCOPE_PACKET_SIZE])

        for sample_index in range(SCOPE_SAMPLES_PER_PACKET):
            start = sample_index * SCOPE_SAMPLE_SIZE
            raw_sample = packet[start : start + SCOPE_SAMPLE_SIZE]
            decoded = decode_scope_sample(
                raw_sample,
                timestamp_state,
                packet_index=packet_index,
                sample_index=sample_index,
                is_epr=is_epr,
                product_id=product_id,
            )
            if decoded is not None:
                samples.append(decoded)

    return ScopeTransferDecode(
        complete_packets=packet_count,
        samples=tuple(samples),
        paddings=tuple(paddings),
        residual=residual,
    )


def scope_graph_preamble(first_sample: ScopeSample) -> tuple[ScopeGraphPoint, ScopeGraphPoint]:
    """
    Reproduce the two synthetic points Analyzer Utility inserts only when its
    graph list is initially empty:

      t-2 us : all values zero
      t-1 us : first sample's values

    The actual first ScopeSample at t is not duplicated here.
    """
    first = first_sample
    return (
        ScopeGraphPoint(
            timestamp_us=first.timestamp_us - 2,
            cc1_mV=0,
            cc2_mV=0,
            ibus_mA=0,
            vbus_mV=0,
        ),
        ScopeGraphPoint(
            timestamp_us=first.timestamp_us - 1,
            cc1_mV=first.cc1_mV,
            cc2_mV=first.cc2_mV,
            ibus_mA=first.ibus_mA,
            vbus_mV=first.vbus_mV,
        ),
    )


