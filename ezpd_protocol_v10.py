# Helpers --------------------------------------------------------------------

def get_bits(value: int, shift: int, width: int) -> int:
    if shift < 0 or width <= 0:
        raise ValueError("invalid bit field")
    return (int(value) >> shift) & ((1 << width) - 1)


def read_u16_le(data: bytes, offset: int = 0) -> int:
    end = offset + 2
    if offset < 0 or end > len(data):
        raise ValueError("uint16 read exceeds buffer")
    return int.from_bytes(data[offset:end], "little", signed=False)


def read_u32_le(data: bytes, offset: int = 0) -> int:
    end = offset + 4
    if offset < 0 or end > len(data):
        raise ValueError("uint32 read exceeds buffer")
    return int.from_bytes(data[offset:end], "little", signed=False)


def write_u32_le(value: int) -> bytes:
    value = int(value)
    if not 0 <= value <= 0xFFFFFFFF:
        raise ValueError("value must fit uint32")
    return value.to_bytes(4, "little", signed=False)


def decode_packet_word(word: int) -> dict[str, int]:
    word = int(word) & 0xFFFFFFFF
    return {
        name: get_bits(word, shift, width)
        for name, (shift, width) in PACKET_WORD_FIELDS.items()
    }


def get_message_class_from_fields(*, extended: int, obj_count: int) -> str:
    if int(extended):
        return "EXTENDED"
    if int(obj_count):
        return "DATA"
    return "CONTROL"


def get_message_class(word: int) -> str:
    fields = decode_packet_word(word)
    return get_message_class_from_fields(
        extended=fields["EXTENDED"],
        obj_count=fields["OBJ_COUNT"],
    )


def get_message_name(msg_class: str, msg_type: int, default: Optional[str] = None):
    key = str(msg_class).upper()
    table = MESSAGE_TYPES_BY_CLASS.get(key)
    if table is None:
        if default is not None:
            return default
        raise KeyError(f"unknown message class: {msg_class!r}")
    idx = int(msg_type)
    return table[idx] if 0 <= idx < len(table) else default


def get_message_name_from_word(word: int, default: Optional[str] = None):
    fields = decode_packet_word(word)
    cls = get_message_class_from_fields(
        extended=fields["EXTENDED"],
        obj_count=fields["OBJ_COUNT"],
    )
    return get_message_name(cls, fields["MSG_TYPE"], default)


def decode_extended_header(header: int) -> dict[str, int]:
    """Decode the USB-PD 16-bit Extended Message Header fields confirmed here."""
    header = int(header) & 0xFFFF
    return {
        "raw": header,
        "data_size": header & EXTENDED_DATA_SIZE_MASK,
        "request_chunk": (header >> EXTENDED_REQUEST_CHUNK_BIT) & 1,
        "chunk_no": (header >> EXTENDED_CHUNK_NO_SHIFT) & EXTENDED_CHUNK_NO_MASK,
        "chunked": (header >> EXTENDED_CHUNKED_BIT) & 1,
    }


def split_capture_transfer(data: bytes) -> list[bytes]:
    """
    Split one complete EP81 bulk transfer into its 64-byte capture records.

    Confirmed CY4500-EPR framing:
        idle transfer:
            AA AB AC AD

        data transfer:
            [64-byte record] * N + AA AB AC AD

    This function is intentionally strict. It preserves USB-transfer framing
    assumptions instead of silently concatenating malformed or partial reads.
    """
    data = bytes(data)

    if data == EP81_TRANSFER_TERMINATOR:
        return []

    if len(data) < len(EP81_TRANSFER_TERMINATOR):
        raise ValueError(
            f"EP81 transfer too short: {len(data)} bytes"
        )

    if not data.endswith(EP81_TRANSFER_TERMINATOR):
        raise ValueError(
            "EP81 transfer is missing AA AB AC AD terminator"
        )

    payload = data[:-len(EP81_TRANSFER_TERMINATOR)]

    if not payload:
        raise ValueError(
            "empty payload before EP81 terminator; expected idle marker only"
        )

    if len(payload) % CAPTURE_RECORD_SIZE:
        raise ValueError(
            f"EP81 payload is not {CAPTURE_RECORD_SIZE}-byte aligned: "
            f"{len(payload)} bytes"
        )

    return [
        payload[offset:offset + CAPTURE_RECORD_SIZE]
        for offset in range(0, len(payload), CAPTURE_RECORD_SIZE)
    ]


def normal_packet_effective_size(obj_count: int) -> int:
    n = int(obj_count)
    if not 0 <= n <= 7:
        raise ValueError("obj_count must be 0..7")
    return NORMAL_PACKET_BASE_SIZE + n * DATA_OBJECT_SIZE


def extended_record_count(data_size: int) -> int:
    n = int(data_size)
    if not 0 <= n <= 0x1FF:
        raise ValueError("Extended data_size must be 0..511")
    total = n + EXTENDED_HEADER_SIZE
    return (total + EXTENDED_BYTES_PER_RECORD - 1) // EXTENDED_BYTES_PER_RECORD


def vbus_epr_raw_scale(raw: int) -> int:
    raw = int(raw)
    if raw < 0:
        raise ValueError("raw must be >= 0")
    return raw * VBUS_EPR_MULTIPLIER * VBUS_EPR_GAIN // VBUS_EPR_DIVISOR


def vbus_legacy_raw_scale(raw: int) -> int:
    raw = int(raw)
    if raw < 0:
        raise ValueError("raw must be >= 0")
    return raw * VBUS_LEGACY_MULTIPLIER * VBUS_LEGACY_GAIN // VBUS_LEGACY_DIVISOR



def live_ibus_milliamps(raw1: int) -> int:
    """
    Analyzer Utility 4.2.0 live-current conversion.

        IBUS[mA] = abs(raw1 - 2048) * 100 // 36

    This intentionally reproduces the Utility's integer arithmetic.
    """
    raw1 = int(raw1)
    if not 0 <= raw1 <= 0xFFFF:
        raise ValueError("raw1 must fit uint16")

    return (
        abs(raw1 - LIVE_CURRENT_ZERO_RAW)
        * LIVE_CURRENT_NUMERATOR_MA
        // LIVE_CURRENT_DENOMINATOR_COUNTS
    )


def live_ibus_amps(raw1: int, *, clamp_display_zero: bool = False) -> float:
    """
    Return Analyzer Utility 4.2.0 live current in amperes.

    clamp_display_zero is retained for API compatibility with v6; the exact
    Utility formula is already non-negative because it uses abs().
    """
    current = live_ibus_milliamps(raw1) / 1000.0
    if clamp_display_zero and current < 0.0:
        return 0.0
    return current


def _live_voltage_params(*, is_epr: bool, product_id: int) -> tuple[int, int]:
    """
    Reproduce Analyzer Utility 4.2.0 factor/val selection.

    Only the EPR + PID 0xFDEF combination switches to factor=12,val=4048.
    All other cases use the legacy factor=11,val=3296 path.
    """
    if is_epr and int(product_id) == USB_PID_CY4500_EPR:
        return LIVE_FDEF_VBUS_FACTOR, LIVE_FDEF_ADC_REF_MV
    return LIVE_LEGACY_VBUS_FACTOR, LIVE_LEGACY_ADC_REF_MV


def decode_live_status_response(
    data: bytes,
    *,
    is_epr: bool = True,
    product_id: int = USB_PID_CY4500_EPR,
) -> dict[str, object]:
    """
    Decode the exact 8-byte CMD_GET_VOLT_AMP response using the Analyzer
    Utility 4.2.0 VoltAmpUpdater formulas.

    Layout:
      word0 = VBUS ADC raw
      word1 = IBUS ADC raw
      word2 = CC1 ADC raw
      word3 = CC2 ADC raw
    """
    data = bytes(data)
    if len(data) != LIVE_STATUS_RESPONSE_SIZE:
        raise ValueError(
            f"live status response must be exactly "
            f"{LIVE_STATUS_RESPONSE_SIZE} bytes, got {len(data)}"
        )

    raw0 = int.from_bytes(data[0:2], "little")
    raw1 = int.from_bytes(data[2:4], "little")
    raw2 = int.from_bytes(data[4:6], "little")
    raw3 = int.from_bytes(data[6:8], "little")

    factor, val_mv = _live_voltage_params(
        is_epr=is_epr,
        product_id=product_id,
    )

    vbus_mV = raw0 * val_mv * factor // LIVE_ADC_COUNTS
    ibus_mA = live_ibus_milliamps(raw1)
    cc1_mV = raw2 * val_mv // LIVE_ADC_COUNTS
    cc2_mV = raw3 * val_mv // LIVE_ADC_COUNTS

    return {
        "raw": data,
        "raw0": raw0,
        "raw1": raw1,
        "raw2": raw2,
        "raw3": raw3,

        "vbus_raw": raw0,
        "ibus_raw": raw1,
        "cc1_raw": raw2,
        "cc2_raw": raw3,

        "vbus_mV": vbus_mV,
        "vbus_V": vbus_mV / 1000.0,
        "ibus_mA": ibus_mA,
        "ibus_A": ibus_mA / 1000.0,
        "ibus_display_A": ibus_mA / 1000.0,
        "cc1_mV": cc1_mV,
        "cc1_V": cc1_mV / 1000.0,
        "cc2_mV": cc2_mV,
        "cc2_V": cc2_mV / 1000.0,

        "power_W": (vbus_mV * ibus_mA) / 1_000_000.0,

        "live_factor": factor,
        "live_val_mV": val_mv,
        "live_vbus_scale_status": "ANALYZER_UTILITY_4_2_0_EXACT",
        "live_current_scale_status": "ANALYZER_UTILITY_4_2_0_EXACT",
        "cc_semantics": "CC1_CC2_CONFIRMED",
    }



